"""
embedding_model.py  (generated by the training notebook - do not edit by hand)

Turns an image into a 256-number vector using a CNN that was trained from scratch on CIFAR-100.
The project uses only:  load_encoder(), ImageEncoder.get_embedding(), ImageEncoder.get_embedding_and_label()
"""
import os

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision import transforms

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
IMAGE_SIZE = 32          # images are resized to 32x32, exactly like in training
EMBEDDING_DIM = 256


class ResBlock(nn.Module):
    def __init__(self, cin, cout, stride):
        super().__init__()
        self.conv1 = nn.Conv2d(cin, cout, 3, stride, 1, bias=False); self.bn1 = nn.BatchNorm2d(cout)
        self.conv2 = nn.Conv2d(cout, cout, 3, 1, 1, bias=False);     self.bn2 = nn.BatchNorm2d(cout)
        if stride == 1 and cin == cout:
            self.skip = nn.Identity()
        else:
            self.skip = nn.Sequential(nn.Conv2d(cin, cout, 1, stride, bias=False), nn.BatchNorm2d(cout))

    def forward(self, x):
        out = F.relu(self.bn1(self.conv1(x)))
        out = self.bn2(self.conv2(out))
        return F.relu(out + self.skip(x))          # skip connection: add the input back


class EmbeddingResNet(nn.Module):
    def __init__(self, emb_dim=EMBEDDING_DIM, num_classes=100):
        super().__init__()
        self.stem = nn.Sequential(nn.Conv2d(3, 64, 3, 1, 1, bias=False), nn.BatchNorm2d(64), nn.ReLU())
        self.blocks = nn.Sequential(
            ResBlock(64, 64, 1),   ResBlock(64, 64, 1),
            ResBlock(64, 128, 2),  ResBlock(128, 128, 1),
            ResBlock(128, 256, 2), ResBlock(256, 256, 1),
            ResBlock(256, 512, 2), ResBlock(512, 512, 1))
        self.embedding_layer = nn.Sequential(nn.Linear(512, emb_dim), nn.BatchNorm1d(emb_dim))
        self.classifier = nn.Linear(emb_dim, num_classes)

    def forward(self, x, return_embedding=False):
        x = self.blocks(self.stem(x))
        x = F.adaptive_avg_pool2d(x, 1).flatten(1)       # global average pooling
        emb = self.embedding_layer(x)
        if return_embedding:
            return emb
        return self.classifier(emb), emb


class ImageEncoder:
    """Loads embedding_model.pth once and converts PIL images into vectors."""

    def __init__(self, checkpoint_path="embedding_model.pth"):
        if not os.path.exists(checkpoint_path):
            raise FileNotFoundError(
                f"Trained model not found at {checkpoint_path}. "
                "Run the training notebook and copy embedding_model.pth next to this file.")
        ckpt = torch.load(checkpoint_path, map_location=DEVICE, weights_only=True)
        if ckpt.get("arch") != "EmbeddingResNet":
            raise ValueError("This checkpoint was not created by the final training notebook "
                             "(expected arch='EmbeddingResNet'). Retrain with the final notebook.")

        self.embedding_dim = int(ckpt["embedding_dim"])
        self.class_names = list(ckpt["class_names"])
        self.image_size = int(ckpt.get("image_size", IMAGE_SIZE))
        self.test_accuracy = ckpt.get("test_accuracy")

        self.transform = transforms.Compose([
            transforms.Resize((self.image_size, self.image_size)),
            transforms.ToTensor(),
            transforms.Normalize(mean=ckpt["mean"], std=ckpt["std"]),
        ])

        self.model = EmbeddingResNet(self.embedding_dim, len(self.class_names))
        self.model.load_state_dict(ckpt["model_state_dict"])
        self.model.to(DEVICE).eval()

    def _prepare(self, image):
        return self.transform(image.convert("RGB")).unsqueeze(0).to(DEVICE)

    @torch.no_grad()
    def get_embedding(self, image):
        """PIL image -> numpy float32 vector of length embedding_dim (not yet L2-normalised)."""
        emb = self.model(self._prepare(image), return_embedding=True)
        return emb.cpu().numpy()[0].astype("float32")

    @torch.no_grad()
    def get_embedding_and_label(self, image):
        """PIL image -> (vector, predicted class name, confidence 0..1)."""
        logits, emb = self.model(self._prepare(image))
        probs = F.softmax(logits, dim=1)[0]
        conf, idx = torch.max(probs, dim=0)
        return emb.cpu().numpy()[0].astype("float32"), self.class_names[idx.item()], float(conf.item())


def load_encoder(checkpoint_path="embedding_model.pth"):
    return ImageEncoder(checkpoint_path)
